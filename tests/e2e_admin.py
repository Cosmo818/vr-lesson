def api(path, body=None, tok='', method='POST'):
    rq = urllib.request.Request('http://127.0.0.1:8777' + path, data=None if body is None else json.dumps(body).encode(), method=method, headers={'Content-Type': 'application/json', 'Authorization': 'Bearer ' + tok})
    try:
        r = urllib.request.urlopen(rq, timeout=5); return r.status, json.loads(r.read() or b'{}')
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b'{}')


